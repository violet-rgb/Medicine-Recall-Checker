def _answer_from_web_search(identity: dict) -> dict:
    """Fallback path: nothing in the vector DB, so ask Gemini to research it live
    using Google Search grounding."""
    medicine_name = identity.get("brand_name") or identity.get("generic_name") or "Unknown Medicine"
    batch_number = identity.get("batch_number")
    manufacturer = identity.get("manufacturer") or ""

    query = f"{medicine_name} {f'batch {batch_number}' if batch_number else ''} {manufacturer} recall"

    prompt = f"""Research whether the medicine "{medicine_name}" (batch: {batch_number},
manufacturer: {manufacturer}) has been recalled by health authorities (such as US FDA, CDSCO, etc.). 
Use web search to check for active product recall alerts related to this medicine and batch.

If you find a recall matching this batch (or if all batches of this product are recalled), return the recall details.
If no recall matches this batch/product, state that it is not recalled.

Respond with ONLY a JSON object as your final message (no markdown fences, no extra commentary):
{{
  "medicine_name": "<best identified name>",
  "batch_number": "<batch number checked>",
  "manufacturer": "<manufacturer checked, or null>",
  "is_recalled": true|false|null,
  "recall_date": "<date of recall (YYYY-MM-DD or Month YYYY) if recalled, or null>",
  "recall_reason": "<1-2 sentence description of the recall reason if recalled, or null>",
  "recalling_agency": "<regulatory agency e.g. 'US FDA', 'CDSCO', or null>",
  "recall_class": "<recall classification e.g. 'Class I', 'Class II', or null>",
  "recommendation": "<advisory warning/recommendation for patient if recalled, or null>",
  "status_summary": "<1-2 sentence summary of recall status>",
  "general_info": "<1-2 sentences context from the search results, e.g. date of search validation>",
  "source": "web_search"
}}"""

    resp = _generate_with_model_fallback(
        contents=prompt,
        config=types.GenerateContentConfig(
            max_output_tokens=3000,
            tools=[types.Tool(google_search=types.GoogleSearch())],
            thinking_config=types.ThinkingConfig(thinking_budget=0),
        ),
    )
    final_text = (resp.text or "{}").strip()

    try:
        parsed = _parse_json_response(final_text)
        if parsed.get("is_recalled") == "true" or parsed.get("is_recalled") is True:
            parsed["is_recalled"] = True
        elif parsed.get("is_recalled") == "false" or parsed.get("is_recalled") is False:
            parsed["is_recalled"] = False
        return parsed
    except Exception as e:
        print(f"[llm] Parsing web search failed: {e}")
        return {
            "medicine_name": medicine_name,
            "batch_number": batch_number,
            "manufacturer": manufacturer,
            "is_recalled": None,
            "recall_date": None,
            "recall_reason": None,
            "recalling_agency": None,
            "recall_class": None,
            "recommendation": "Please verify this batch status manually on the official FDA or CDSCO websites.",
            "status_summary": "Web search ran but the result could not be parsed reliably.",
            "general_info": "An error occurred parsing the search results.",
            "source": "web_search",
        }


def analyze_medicine(raw_ocr_text: str, manual_batch: str = "", manual_med: str = "") -> dict:
    """Full pipeline: identity extraction -> vector DB lookup -> web fallback."""
    global _web_search_available
    identity = extract_medicine_identity(raw_ocr_text)
    print(f"[llm] Extracted identity: {identity}")
    # Merge manual inputs if provided
    manual_batch = (manual_batch or "").strip()
    manual_med = (manual_med or "").strip()

    if manual_batch:
        identity["batch_number"] = manual_batch
    if manual_med:
        identity["brand_name"] = manual_med

    # Recalculate search query if manual inputs changed things
    if manual_batch or manual_med:
        query_parts = []
        if identity.get("brand_name"):
            query_parts.append(identity["brand_name"])
        if identity.get("batch_number"):
            query_parts.append(f"batch {identity['batch_number']}")
        identity["search_query"] = " ".join(query_parts).strip()

    batch = identity.get("batch_number") or ""
    med = identity.get("brand_name") or identity.get("generic_name") or ""

    if not batch:
        result = _answer_without_batch_number(identity)
        result["identity"] = identity
        result["disclaimer"] = DISCLAIMER
        return result

    matches = search_recalled_db(batch_number=batch, medicine_name=med)

    recalled_matches = [match for match in matches if match.get("is_recalled") is True]

    if recalled_matches:
        result = _answer_from_vector_matches(identity, recalled_matches)
    elif matches:
        result = _answer_from_known_safe_db_match(identity, matches)
    elif ENABLE_WEB_SEARCH and _web_search_available:
        try:
            result = _answer_from_web_search(identity)
        except Exception as e:
            print(f"[llm] Web search fallback failed: {e}")
            if "RESOURCE_EXHAUSTED" in str(e) or "quota" in str(e).lower():
                _web_search_available = False
                print("[llm] Disabling further web search attempts until restart due to quota limits.")
            result = _answer_without_web_search(identity)
    else:
        result = _answer_without_web_search(identity)

    result["identity"] = identity
    result["disclaimer"] = DISCLAIMER
    return result
